import 'protocol.dart';

/// Builds a Clash / mihomo config snippet that sends the campus resources
/// pushed by the server to PureConnect's local SOCKS5 (or HTTP) listener.
///
/// Intended use: Clash runs as the only VPN (TUN), PureConnect runs in
/// proxy-only mode, and these rules are pasted (or merged) into Clash.
String buildClashRules(SessionInfo s, {String name = 'PureConnect'}) {
  final b = StringBuffer();
  b.writeln('# Generated by PureConnect from ${s.server} (${s.protocol})');
  b.writeln('# Merge into your Clash / mihomo config. Put these rules above MATCH.');

  final (type, bind) = s.socksBind.isNotEmpty ? ('socks5', s.socksBind) : ('http', s.httpBind);
  final (host, port) = _splitHostPort(bind);
  b.writeln('proxies:');
  if (bind.isEmpty) {
    b.writeln('  # SOCKS5/HTTP listener is off in PureConnect; enable one and export again.');
  }
  b.writeln('  - name: "$name"');
  b.writeln('    type: $type');
  b.writeln('    server: ${host.isEmpty || host == '0.0.0.0' || host == '::' ? '127.0.0.1' : host}');
  b.writeln('    port: ${port ?? (type == 'socks5' ? 1080 : 1081)}');
  if (type == 'socks5') b.writeln('    udp: true');
  b.writeln();

  final doms = {for (final d in s.domainResources) _cleanDomain(d)}..remove('');
  final domains = doms
      .where((d) => !doms.any((o) => o != d && d.endsWith('.$o')))
      .toList()
    ..sort();
  final seen = <String>{};
  final rules = <String>[];
  void add(String r) {
    if (seen.add(r)) rules.add(r);
  }

  if (s.dnsServer.isNotEmpty && domains.isNotEmpty) {
    b.writeln('dns:');
    b.writeln('  nameserver-policy:');
    for (final dom in domains) {
      b.writeln("    '+.$dom': '${s.dnsServer}#$name'");
    }
    b.writeln();
  }

  for (final dom in domains) {
    add('DOMAIN-SUFFIX,$dom,$name');
  }
  for (final r in s.ipResources) {
    for (final c in rangeToCidrs(r.ipMin, r.ipMax)) {
      add('IP-CIDR,$c,$name,no-resolve');
    }
  }
  for (final r in s.routes) {
    if (r.contains('/') && !r.contains(':') && r != '0.0.0.0/0') add('IP-CIDR,$r,$name,no-resolve');
  }

  b.writeln('rules:');
  if (rules.isEmpty) b.writeln('  # The server pushed no resources.');
  for (final r in rules) {
    b.writeln('  - $r');
  }
  return b.toString();
}

String _cleanDomain(String d) {
  var x = d.trim().toLowerCase();
  x = x.replaceFirst(RegExp(r'^[a-z]+://'), '');
  x = x.split('/').first.split(':').first;
  while (x.startsWith('*.') || x.startsWith('.')) {
    x = x.substring(x.startsWith('*.') ? 2 : 1);
  }
  return x.contains('*') ? '' : x;
}

(String, int?) _splitHostPort(String bind) {
  if (bind.isEmpty) return ('', null);
  final i = bind.lastIndexOf(':');
  if (i < 0) return (bind, null);
  return (bind.substring(0, i).replaceAll('[', '').replaceAll(']', ''), int.tryParse(bind.substring(i + 1)));
}

int? _ip4(String s) {
  final p = s.trim().split('.');
  if (p.length != 4) return null;
  var v = 0;
  for (final x in p) {
    final n = int.tryParse(x);
    if (n == null || n < 0 || n > 255) return null;
    v = (v << 8) | n;
  }
  return v;
}

String _fmt(int v) => '${(v >> 24) & 255}.${(v >> 16) & 255}.${(v >> 8) & 255}.${v & 255}';

/// Minimal set of CIDR blocks covering [min, max] (IPv4 only).
List<String> rangeToCidrs(String min, String max) {
  var lo = _ip4(min);
  final hi = _ip4(max.isEmpty ? min : max);
  if (lo == null || hi == null || lo > hi) return const [];
  final out = <String>[];
  while (lo! <= hi) {
    var size = 32;
    while (size > 0) {
      final mask = (1 << (32 - (size - 1))) - 1;
      if ((lo & mask) != 0) break;
      if (lo + mask > hi) break;
      size--;
    }
    out.add('${_fmt(lo)}/$size');
    final next = lo + (1 << (32 - size));
    if (next > 0xFFFFFFFF) break;
    lo = next;
  }
  return out;
}
